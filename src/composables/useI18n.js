const getInitialLang = () => {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('portfolio_lang')
    if (saved === 'en' || saved === 'fr') return saved
    if (navigator.language && navigator.language.startsWith('en')) {
      return 'en'
    }
  }
  return 'fr'
}

